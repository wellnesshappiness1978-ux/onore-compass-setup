export const hasDeepCompatibility = (plan: unknown) => ['vip','b2b','b2b-premium'].includes(normalizePlan(plan));
export const consultationAllowanceText = (language: Language, plan: unknown) => { const c = planBenefitsCopy[language]; const cap=getPlanConsultationLimit(plan); return Number.isFinite(cap) ? c.daily.replace('{n}',String(cap)) : c.unlimited; };
export const billingErrorText = (language: Language, code: BillingErrorCode) => planBenefitsCopy[language][code];
export function planBenefits(plan: Plan, language: Language): string[] {
 const c=planBenefitsCopy[language];
 const base=plan==='free'?[c.basic]:plan==='standard'?[c.seventeen,c.biorhythm]:[c.full,c.biorhythm,c.compatibility,c.mandala];
 if(plan==='b2b'||plan==='b2b-premium')base.push(c.vipAll,c.multiple,c.roster.replace('{n}',String(plan==='b2b'?30:100)));
 return [...base, consultationAllowanceText(language,plan)];
}
